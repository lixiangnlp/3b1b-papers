# 送进 TTS 前的读音替换：屏幕上显示的写法 -> 更容易读对的写法。
TTS_REPLACEMENTS: dict[str, str] = {
    "SMH-Bench": "S M H Bench",
    "HomeEnv": "Home Env",
    "API": "A P I",
    "DR": "D R",
    "EIA": "E I A",
    "ReAct": "React",
    "2606.01912": "二六零六点零一九一二",
}


def speakable(text: str) -> str:
    for src, dst in TTS_REPLACEMENTS.items():
        text = text.replace(src, dst)
    return text
